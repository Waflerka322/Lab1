-- Главная таблица: Факультеты (первичный ключ с автоинкрементом)
CREATE TABLE faculties (
    faculty_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_name character varying(255) NOT NULL,
    foundation_date date NOT NULL,
    activity_type character varying(255) NOT NULL,
    max_students integer NOT NULL CHECK (max_students > 0)
);

-- Зависимая таблица: Группы (строковый номер группы и каскадные связи)
CREATE TABLE groups (
    group_id character varying(50) PRIMARY KEY,
    max_people integer NOT NULL CHECK (max_people > 0),
    faculty_id integer NOT NULL,
    curator character varying(255) NOT NULL,
    CONSTRAINT fk_groups_faculty FOREIGN KEY (faculty_id) 
        REFERENCES faculties (faculty_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


