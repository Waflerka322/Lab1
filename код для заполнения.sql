INSERT INTO techfacultygroups (faculty_id, faculty_name, activity_type, max_students, group_id, group_name, max_people, curator)
SELECT 
    f.faculty_id,
    f.faculty_name,
    f.activity_type,
    f.max_students,
    g.group_id,
    g.group_name,
    g.max_people,
    g.curator
FROM groups g
JOIN faculties f ON g.faculty_id = f.faculty_id
WHERE f.activity_type = 'Техническая';
